/**
 * 响应式断点常量（JS 侧唯一来源）
 *
 * 全站响应式判断统一走这里，不要在组件里再写魔法数字。
 *
 * ## 档位设计
 *
 * 只保留三档，且与 Tailwind 默认断点对齐，这样手写 @media 和 Tailwind 工具类
 * （`sm:` / `md:` / `lg:`）语义一致，不会互相打架：
 *
 * | 常量     | 值   | Tailwind | 含义                                                     |
 * | -------- | ---- | -------- | -------------------------------------------------------- |
 * | MOBILE   | 640  | sm       | 手机：弹窗全屏、触控区放大到 44px、表格降级为卡片列表      |
 * | HANDHELD | 768  | md       | 手持设备上限：侧栏改抽屉、宽表格改用卡片列表              |
 * | COMPACT  | 1180 | —        | 小笔记本 / 平板横屏：分页与固定列的内边距收紧              |
 *
 * ## HANDHELD 为什么是 768
 *
 * 业务表格普遍带左右固定列（以会员管理为例：左固定 130px + 右固定 260px = 390px）。
 * 固定列永远不参与横向滚动，所以可用宽度必须显著大于 390px，中间的数据列才不至于被压成零宽。
 * 768px 是实测下来「固定列放得下、数据列还剩得下可读宽度」的最小值，
 * 低于它就一律走卡片列表（见 `MobileCardList`）。
 *
 * ## 注意事项
 *
 * 1. 改这里的值必须同步改 `src/assets/styles/core/breakpoint.scss`（SCSS 无法直接读 TS 常量）
 * 2. 新增断点前先问：能不能复用上面三档？能复用就不要加第四档
 *
 * @module breakpoints
 */

export const BREAKPOINTS = {
  /** 手机上限 */
  MOBILE: 640,
  /** 手持设备上限（侧栏抽屉化、表格降级为卡片） */
  HANDHELD: 768,
  /** 小笔记本 / 平板横屏上限 */
  COMPACT: 1180
} as const

/** 触控区最小尺寸（px）。老师是站着单手操作，低于这个值容易点错 */
export const TOUCH_TARGET_MIN = 44
